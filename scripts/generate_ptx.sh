# Regenerates src/kernels_ptx.h from src/kernels.cu.
#
# The PTX is relabelled to target sm_52 with PTX ISA 7.0 (CUDA 11.0), so drivers from
# CUDA 11 on can JIT it for any GPU they support. That is valid because the kernels only
# use instructions every PTX ISA has; the script refuses to relabel anything else.
set -euo pipefail
cd "$(dirname "$0")/.."
nvcc="${NVCC:-nvcc}"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

"$nvcc" -arch=compute_75 -ptx src/kernels.cu -o "$tmp/kernels.ptx"

allowed='^(mov|add|ld|st|cvt|cvta|ret|setp|mul|shl|or|bra|mad|and)$'
if grep -oE '^\s+(@%p[0-9]+\s+)?[a-z]+' "$tmp/kernels.ptx" | awk '{print $NF}' | sort -u | grep -vE "$allowed"; then
    echo "error: kernels.cu now uses PTX instructions not checked against PTX ISA 7.0 (listed above)" >&2
    exit 1
fi

{
    echo "// Copyright 2026 Tyler Casper"
    echo "// SPDX-License-Identifier: Apache-2.0"
    echo
    echo "// Generated by scripts/generate_ptx.sh from src/kernels.cu. Do not edit."
    echo "#pragma once"
    echo
    echo "namespace wslcg::detail {"
    echo "inline constexpr char kKernelsPtx[] = R\"PTX("
    sed -E -e 's/^\.version .*/.version 7.0/' -e 's/^\.target .*/.target sm_52/' \
        -e '/^\/\/ (Generated by|Compiler Build|Cuda compilation|Based on)/d' "$tmp/kernels.ptx"
    echo ")PTX\";"
    echo "} // namespace wslcg::detail"
} > src/kernels_ptx.h
echo "wrote src/kernels_ptx.h"
